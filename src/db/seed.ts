function toFeminineSurname(surname: string): string {
  if (/(ов|ев|ёв|ин|ын)$/.test(surname)) return `${surname}а`;
  if (/(ский|цкий)$/.test(surname)) return `${surname.slice(0, -2)}ая`;
  return surname;
}

