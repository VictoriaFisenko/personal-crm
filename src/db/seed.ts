const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "kh", ц: "ts", ч: "ch", ш: "sh",
  щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

function transliterate(text: string): string {
  return Array.from(text.toLowerCase())
    .map((char) => TRANSLIT[char] ?? "")
    .join("");
}

function pickGroup(): Group {
  const total = GROUPS.reduce((sum, group) => sum + group.weight, 0);
  let roll = random() * total;
  for (const group of GROUPS) {
    roll -= group.weight;
    if (roll < 0) return group;
  }
  return GROUPS[0];
}

function makeName(gender: Gender, group: Group, persona: Persona) {
  const firstName = pick(gender === "m" ? MALE_NAMES : FEMALE_NAMES);

  // "Марина Сергеевна": how one saves a teacher, a doctor or an older neighbour.
  if (group.formal && chance(0.25)) {
    const patronymic = pick(
      gender === "m" ? MALE_PATRONYMICS : FEMALE_PATRONYMICS,
    );
    return {
      name: `${firstName} ${patronymic}`,
      emailBase: `${transliterate(firstName)}${randomInt(70, 99)}`,
      usesTag: false,
    };
  }

  // "Саша из спортзала": no surname, just where the person is from.
  const shortName = SHORT_NAMES[firstName];
  if (persona.tag && shortName && chance(0.35)) {
    return {
      name: `${shortName} ${persona.tag}`,
      emailBase: `${transliterate(shortName)}${randomInt(70, 99)}`,
      usesTag: true,
    };
  }

  const surname = pick(SURNAMES);
  const fullSurname = gender === "m" ? surname : toFeminineSurname(surname);
  const first = transliterate(firstName);
  const last = transliterate(fullSurname);

  return {
    name: `${firstName} ${fullSurname}`,
    emailBase: pick([
      `${first}.${last}`,
      `${first[0]}.${last}`,
      `${last}.${first}`,
      `${first}_${last}`,
    ]),
    usesTag: false,
  };
}

function makePhone(): string {
  const digits = String(randomInt(0, 9_999_999)).padStart(7, "0");
  return `+7 000 ${digits.slice(0, 3)}-${digits.slice(3, 5)}-${digits.slice(5)}`;
}

function makeNoteCount(): number {
  const roll = random();
  if (roll < 0.25) return 0;
  if (roll < 0.55) return 1;
  if (roll < 0.77) return 2;
  if (roll < 0.9) return 3;
  return randomInt(4, 6);
}

function makeNoteBodies(
  group: Group,
  persona: Persona,
  gender: Gender,
  count: number,
) {
  // Persona notes are listed twice so the specific ones show up more often.
  const specific = [
    ...group.notes,
    ...(persona.notes ?? []),
    ...(persona.notes ?? []),
  ];
  const limit = Math.min(
    count,
    new Set(specific).size + (group.personal ? PERSONAL_NOTES.length : 0),
  );

  const bodies = new Set<string>();
  while (bodies.size < limit) {
    const roll = random();
    if (group.personal && roll < 0.08) {
      bodies.add(
        `День рождения ${randomInt(1, 28)} ${pick(BIRTHDAY_MONTHS)} — не забыть поздравить.`,
      );
    } else if (group.personal && roll < 0.3) {
      bodies.add(conjugate(pick(PERSONAL_NOTES), gender));
    } else {
      bodies.add(conjugate(pick(specific), gender));
    }
  }
  return [...bodies];
}

function generate(now: number) {
  const usedNames = new Set<string>();
  const usedEmails = new Set<string>();
  const people = [];

  while (people.length < CONTACT_COUNT) {
    const group = pickGroup();
    const persona = pick(group.personas);
    const gender: Gender = persona.gender ?? (chance(0.5) ? "m" : "f");

    const { name, emailBase, usesTag } = makeName(gender, group, persona);
    if (usedNames.has(name)) continue;
    usedNames.add(name);

    // "Саша из бегового клуба" does not need "из бегового клуба" repeated.
    const aboutText = phrase(persona.about, gender);
    const about =
      (usesTag && aboutText === persona.tag) || !chance(0.94) ? null : aboutText;

    let email: string | null = null;
    if (chance(0.62)) {
      const domain = pick(["example.com", "example.org", "example.net"]);
      email = `${emailBase}@${domain}`;
      while (usedEmails.has(email)) {
        email = `${emailBase}${randomInt(10, 99)}@${domain}`;
      }
      usedEmails.add(email);
    }

    // Known for anywhere between a couple of weeks and three years.
    const createdAt =
      now - randomInt(14, 3 * 365) * DAY_MS - randomInt(0, DAY_MS);

    const bodies = makeNoteBodies(group, persona, gender, makeNoteCount());
    const noteDates = bodies
      .map(() => createdAt + Math.floor(random() * (now - createdAt)))
      .sort((a, b) => a - b);

    people.push({
      contact: {
        name,
        about,
        howWeMet: chance(0.88) ? pick(persona.met) : null,
        phone: chance(0.88) ? makePhone() : null,
        email,
        createdAt: new Date(createdAt),
      },
      notes: bodies.map((body, index) => ({
        body,
        createdAt: new Date(noteDates[index]),
      })),
    });
  }

  return people;
}

function chunk<T>(items: T[], size: number): T[][] {
  const chunks: T[][] = [];
  for (let i = 0; i < items.length; i += size) {
    chunks.push(items.slice(i, i + size));
  }
  return chunks;
}

async function main() {
  loadEnvConfig(process.cwd());

  const pool = new Pool({ connectionString: getDatabaseUrl() });
  const db = drizzle({ client: pool });

  try {
    const existing = await db.$count(contacts);
    if (existing > 0) {
      console.log(
        `Skipped: the database already has ${existing} contacts. Nothing was changed.`,
      );
      return;
    }

    const people = generate(Date.now());

    const noteCount = await db.transaction(async (tx) => {
      let inserted = 0;

      for (const batch of chunk(people, 250)) {
        const rows = await tx
          .insert(contacts)
          .values(batch.map((person) => person.contact))
          .returning({ id: contacts.id, name: contacts.name });

        // Notes are attached by position, so make sure rows[i] is batch[i].
        const noteRows = batch.flatMap((person, index) => {
          if (rows[index]?.name !== person.contact.name) {
            throw new Error("Inserted contacts came back in an unexpected order");
          }
          return person.notes.map((note) => ({
            ...note,
            contactId: rows[index].id,
          }));
        });

        for (const noteBatch of chunk(noteRows, 500)) {
          await tx.insert(notes).values(noteBatch);
          inserted += noteBatch.length;
        }
      }

      return inserted;
    });

    console.log(`Done: added ${people.length} contacts and ${noteCount} notes.`);
  } finally {
    await pool.end();
  }
}

main().catch((error) => {
  console.error("Seeding failed:", error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
